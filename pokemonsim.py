def evolve():
    global pokemon_name, pokemon_level
    if pokemon_level >= 20 and pokemon_name == "Ivysaur":
        print("\n Your Ivysaur is evolving into a Venusaur! \n")
        pokemon_name = "Venusaur"
        print(case_3())
    elif pokemon_level >= 10 and pokemon_name == "Bulbasaur":
        print("\n Your Bulbasaur is evolving into IVYSAUR! \n")
        pokemon_name = "Ivysaur"
        print(case_2())

def info():
    print("\n--------------------------")
    print(f" Pokémon Name: {pokemon_name}")
    print(f" Level: {pokemon_level}")
    print("--------------------------")
    if pokemon_name == "Bulbasaur":
        print(case_1())
    elif pokemon_name == "Ivysaur":
        print(case_2())
    elif pokemon_name == "Venusaur":
        print(case_3())
    print("--------------------------\n")

def main():
    global pokemon_level, day
    print("Welcome to the Pokemon Evolution Simulator!")
    print("You start with a Bulbasaur. Train it and help it evolve!\n")
    while True:
        print(f"\n--- Day {day} ---")
        print("What would you like to do?")
        print("1. Train")
        print("2. Gym Battle")
        print("3. Display Pokémon Info")
        print("4. Exit")
        choice = input("Enter your choice: ")

        if choice == "1":
            pokemon_level += 1
            day += 1
            flavor = random.choice([
                "Your Pokemon ran laps around the field!",
                "Your Pokemon practiced its special attacks!",
                "Your Pokemon lifted heavy boulders to grow stronger!"
            ])
            print("\n" + flavor)
            print("Your Pokemon gained +1 level!")
            evolve()

        elif choice == "2":
            day += 1
            print("\nYou challenge the local gym...")
            battle_outcome = random.choice(["win", "lose"])
            if battle_outcome == "win":
                print(" Your Pokemon wins the battle! +2 levels!")
                pokemon_level += 2
            else:
                print(" Your Pokemon loses the battle and gains no levels.")
            evolve()

        elif choice == "3":
            info()

        elif choice == "4":
            print("\nThanks for playing! Goodbye!")
            break
        else:
            print("Invalid choice. Try again!")

main()
